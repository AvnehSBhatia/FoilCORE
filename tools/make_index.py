"""Write docs/INDEX.md: every git-tracked file (plus untracked-but-kept data dirs noted), grouped by directory, with sizes.
Run after reorganising:  python tools/make_index.py
"""
from __future__ import annotations

import subprocess
from collections import defaultdict
from pathlib import Path

root = Path(__file__).resolve().parents[1]
files = subprocess.run(["git", "ls-files"], cwd=root, capture_output=True, text=True).stdout.split()
# include files that are new (untracked) but not ignored
files += subprocess.run(["git", "ls-files", "--others", "--exclude-standard"], cwd=root, capture_output=True, text=True).stdout.split()
by_dir: dict[str, list[tuple[str, int]]] = defaultdict(list)
for f in sorted(set(files)):
    p = root / f
    if not p.is_file():
        continue
    by_dir[str(Path(f).parent)].append((Path(f).name, p.stat().st_size))

def hs(n):
    return f"{n/1e6:.1f} MB" if n >= 1e6 else (f"{n/1e3:.0f} KB" if n >= 1e3 else f"{n} B")

out = ["# Repository index (generated by tools/make_index.py)", "",
       "Every file in the repository, by directory. Descriptions of what each directory is for are in `README.md`; this file is the exhaustive listing. Data CSVs (`data/`, 2.8 GB) and local `runs/` are gitignored and not listed.", ""]
total = 0
for d in sorted(by_dir, key=lambda x: (x != ".", x)):
    items = by_dir[d]
    size = sum(s for _, s in items); total += size
    out.append(f"## `{d}/`  ({len(items)} files, {hs(size)})" if d != "." else f"## repository root  ({len(items)} files, {hs(size)})")
    out.append("")
    for name, s in items:
        out.append(f"- `{name}` ({hs(s)})")
    out.append("")
out.append(f"Total: {sum(len(v) for v in by_dir.values())} files, {hs(total)}.")
(root / "docs" / "INDEX.md").write_text("\n".join(out) + "\n")
print("wrote docs/INDEX.md", sum(len(v) for v in by_dir.values()), "files", hs(total))
